CREATE TABLE IF NOT EXISTS person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS listing (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description VARCHAR(4000),
    state VARCHAR(50),
    published_at TIMESTAMP WITH TIME ZONE,
    area VARCHAR(255),
    delivery_mode VARCHAR(50),
    owner_id BIGINT NOT NULL REFERENCES person(id)
);

CREATE TABLE IF NOT EXISTS listing_keywords (
    listing_id BIGINT NOT NULL REFERENCES listing(id),
    keywords VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS favorite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person(id),
    listing_id BIGINT NOT NULL REFERENCES listing(id),
    CONSTRAINT uk_favorite_person_listing UNIQUE (person_id, listing_id)
);

CREATE TABLE IF NOT EXISTS saved_search (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES person(id),
    query VARCHAR(255),
    area VARCHAR(255),
    state VARCHAR(50),
    keyword VARCHAR(255),
    notifications BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS item_lot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL REFERENCES person(id),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS lot_listing (
    item_lot_id BIGINT NOT NULL REFERENCES item_lot(id),
    listings_id BIGINT NOT NULL REFERENCES listing(id),
    PRIMARY KEY (item_lot_id, listings_id)
);

CREATE TABLE IF NOT EXISTS message (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES person(id),
    recipient_id BIGINT NOT NULL REFERENCES person(id),
    listing_id BIGINT REFERENCES listing(id),
    body VARCHAR(4000) NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE
);
